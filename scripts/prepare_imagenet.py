import argparse
import json
import os
import random
from glob import glob
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
import torch
import torch.nn.functional as F
from PIL import Image
from torchvision import models, transforms
from tqdm import tqdm
from transformers import (
    AutoTokenizer,
    Blip2ForConditionalGeneration,
    BlipImageProcessor,
)


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Prepare an ImageNet CSV for Stage-1/Stage-2 training. "
            "Generates Grad-CAM masks and BLIP2 captions."
        )
    )

    parser.add_argument(
        "--imagenet-root",
        type=str,
        required=True,
        help="ImageNet split root containing synset subdirectories.",
    )
    parser.add_argument(
        "--output-csv",
        type=str,
        required=True,
        help="Output CSV path.",
    )
    parser.add_argument(
        "--mask-dir",
        type=str,
        required=True,
        help="Directory in which binary ROI masks are saved.",
    )
    parser.add_argument(
        "--num-images",
        type=int,
        default=None,
        help="Number of randomly sampled images. Default: use all images.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed used for image sampling. Default: 42.",
    )
    parser.add_argument(
        "--mask-threshold",
        type=float,
        default=0.5,
        help="Threshold applied to the normalized Grad-CAM map. Default: 0.5.",
    )
    parser.add_argument(
        "--max-new-tokens",
        type=int,
        default=30,
        help="Maximum number of tokens generated by BLIP2. Default: 30.",
    )
    parser.add_argument(
        "--device",
        type=str,
        default="cuda",
        choices=["cuda", "cpu"],
        help="Device used for preprocessing. Default: cuda.",
    )

    return parser.parse_args()


def build_gradcam_model(device):
    model = models.resnet50(
        weights=models.ResNet50_Weights.IMAGENET1K_V1
    ).to(device)

    model.eval()
    target_layer = model.layer4[-1]

    preprocess = transforms.Compose(
        [
            transforms.Resize((224, 224)),
            transforms.ToTensor(),
            transforms.Normalize(
                mean=[0.485, 0.456, 0.406],
                std=[0.229, 0.224, 0.225],
            ),
        ]
    )

    return model, target_layer, preprocess


def generate_gradcam(
    model,
    target_layer,
    preprocess,
    image,
    device,
):
    activations = {}
    gradients = {}

    def forward_hook(module, inputs, output):
        activations["value"] = output

    def backward_hook(module, grad_input, grad_output):
        gradients["value"] = grad_output[0]

    forward_handle = target_layer.register_forward_hook(forward_hook)
    backward_handle = target_layer.register_full_backward_hook(backward_hook)

    try:
        image_tensor = preprocess(image).unsqueeze(0).to(device)

        output = model(image_tensor)
        predicted_class = output.argmax(dim=1)

        model.zero_grad()
        output[0, predicted_class].backward()

        weights = gradients["value"].mean(
            dim=(2, 3),
            keepdim=True,
        )

        cam = (
            activations["value"] * weights
        ).sum(dim=1, keepdim=True)

        cam = F.relu(cam)
        cam = cam[0, 0].detach().cpu().numpy()

        cam = (
            (cam - cam.min())
            / (cam.max() - cam.min() + 1e-8)
        )

        return cam

    finally:
        forward_handle.remove()
        backward_handle.remove()


def save_binary_mask(
    image,
    cam,
    output_path,
    threshold,
):
    width, height = image.size

    cam = cv2.resize(
        cam,
        (width, height),
    )

    mask = cam > threshold
    mask_uint8 = mask.astype(np.uint8) * 255

    Image.fromarray(mask_uint8).save(output_path)


def build_caption_model(device):
    model_name = "Salesforce/blip2-opt-2.7b"

    dtype = (
        torch.float16
        if device.type == "cuda"
        else torch.float32
    )

    model = Blip2ForConditionalGeneration.from_pretrained(
        model_name,
        torch_dtype=dtype,
    ).to(device)

    model.eval()

    image_processor = BlipImageProcessor.from_pretrained(
        model_name
    )

    tokenizer = AutoTokenizer.from_pretrained(
        model_name,
        use_fast=False,
    )

    return model, image_processor, tokenizer, dtype


@torch.no_grad()
def generate_caption(
    model,
    image_processor,
    tokenizer,
    image,
    device,
    dtype,
    max_new_tokens,
):
    inputs = image_processor(
        images=image,
        return_tensors="pt",
    )

    inputs = {
        key: value.to(
            device=device,
            dtype=dtype,
        )
        if torch.is_floating_point(value)
        else value.to(device)
        for key, value in inputs.items()
    }

    output = model.generate(
        **inputs,
        max_new_tokens=max_new_tokens,
    )

    return tokenizer.decode(
        output[0],
        skip_special_tokens=True,
    )


def load_valid_synsets():
    repo_root = Path(__file__).resolve().parents[1]

    class_index_path = (
        repo_root
        / "dataset"
        / "imagenet_class_index.json"
    )

    with open(class_index_path, "r") as file:
        idx_to_synset = json.load(file)

    return {
        value[0]
        for value in idx_to_synset.values()
    }


def main():
    args = parse_args()

    if args.device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError(
            "CUDA was requested but is not available."
        )

    device = torch.device(args.device)

    os.makedirs(args.mask_dir, exist_ok=True)

    output_parent = os.path.dirname(
        os.path.abspath(args.output_csv)
    )
    os.makedirs(output_parent, exist_ok=True)

    image_paths = sorted(
        glob(
            os.path.join(
                args.imagenet_root,
                "*",
                "*.JPEG",
            )
        )
    )

    if not image_paths:
        raise RuntimeError(
            f"No ImageNet JPEG files found under: "
            f"{args.imagenet_root}"
        )

    if args.num_images is not None:
        if args.num_images > len(image_paths):
            raise ValueError(
                f"--num-images={args.num_images} exceeds "
                f"the available images ({len(image_paths)})."
            )

        random.seed(args.seed)
        image_paths = random.sample(
            image_paths,
            args.num_images,
        )

    valid_synsets = load_valid_synsets()

    gradcam_model, target_layer, gradcam_preprocess = (
        build_gradcam_model(device)
    )

    (
        caption_model,
        image_processor,
        tokenizer,
        caption_dtype,
    ) = build_caption_model(device)

    records = []

    for image_path in tqdm(
        image_paths,
        desc="Preparing dataset",
    ):
        class_id = os.path.basename(
            os.path.dirname(image_path)
        )

        if class_id not in valid_synsets:
            raise ValueError(
                f"Unknown ImageNet synset '{class_id}' "
                f"for image: {image_path}"
            )

        image = Image.open(image_path).convert("RGB")

        cam = generate_gradcam(
            model=gradcam_model,
            target_layer=target_layer,
            preprocess=gradcam_preprocess,
            image=image,
            device=device,
        )

        base_name = os.path.splitext(
            os.path.basename(image_path)
        )[0]

        mask_path = os.path.abspath(
            os.path.join(
                args.mask_dir,
                f"{base_name}_mask.png",
            )
        )

        save_binary_mask(
            image=image,
            cam=cam,
            output_path=mask_path,
            threshold=args.mask_threshold,
        )

        caption = generate_caption(
            model=caption_model,
            image_processor=image_processor,
            tokenizer=tokenizer,
            image=image,
            device=device,
            dtype=caption_dtype,
            max_new_tokens=args.max_new_tokens,
        )

        records.append(
            {
                "jpg": os.path.abspath(image_path),
                "txt": caption,
                "class_id": class_id,
                "mask": mask_path,
            }
        )

    dataframe = pd.DataFrame(
        records,
        columns=[
            "jpg",
            "txt",
            "class_id",
            "mask",
        ],
    )

    dataframe.to_csv(
        args.output_csv,
        index=False,
        encoding="utf-8",
    )

    print()
    print(f"Prepared {len(dataframe)} samples.")
    print(f"CSV saved to: {args.output_csv}")
    print(f"Masks saved to: {args.mask_dir}")


if __name__ == "__main__":
    main()